#!/usr/bin/env node
// Theme pipeline.
//
// `apps/desktop/src/lib/palettes.json` is the single source of truth for every
// palette: the settings grid (via themes.ts) and the CSS custom properties (via
// the generated `styles/themes.css`) are both derived from it, so a palette can
// no longer drift between the swatch and the token block.
//
//   node scripts/gen-themes.mjs            # regenerate themes.css
//   node scripts/gen-themes.mjs --check    # exit 1 if themes.css is stale
//   node scripts/gen-themes.mjs --bootstrap  # (one-off) read palettes out of
//                                             app.css + themes.ts
//
// Light palettes carry their own shadow/star tokens instead of sharing one
// selector list, so every block is self-contained.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const desktop = join(root, 'apps', 'desktop', 'src');
const CSS_OUT = join(desktop, 'styles', 'themes.css');
const JSON_OUT = join(desktop, 'lib', 'palettes.json');

const HEADER = `/* GENERATED by scripts/gen-themes.mjs — do not edit.
   Source: apps/desktop/src/lib/palettes.json
   Regenerate: npm run themes (also runs before dev/build). */
`;

const read = (p) => readFileSync(p, 'utf8');

/** Split a CSS declaration block into [name, value] pairs, in order. */
function declarations(body) {
  const out = [];
  for (const chunk of body.split(';')) {
    const line = chunk.trim();
    if (!line || !line.startsWith('--')) continue;
    const at = line.indexOf(':');
    if (at < 0) continue;
    out.push([line.slice(0, at).trim(), line.slice(at + 1).trim()]);
  }
  return out;
}

function bootstrap() {
  const css = read(join(desktop, 'app.css'));
  const ts = read(join(desktop, 'lib', 'themes.ts'));

  // Metadata (order, label, hint, swatch) as authored in themes.ts.
  const meta = new Map();
  const entry = /\{\s*id:\s*'([^']+)',([^}]*)\}/g;
  for (let m; (m = entry.exec(ts)); ) {
    const body = m[2];
    const field = (name) => {
      const hit = body.match(new RegExp(`${name}:\\s*'([^']*)'`));
      return hit ? hit[1] : undefined;
    };
    meta.set(m[1], {
      id: m[1],
      label: field('label'),
      hint: field('hint'),
      bg: field('bg'),
      accent: field('accent'),
      fg: field('fg'),
      scheme: field('scheme'),
    });
  }

  // Per-theme token blocks.
  const tokens = new Map();
  const block = /:root\[data-theme='([^']+)'\]\s*\{([^}]*)\}/g;
  for (let m; (m = block.exec(css)); ) tokens.set(m[1], new Map(declarations(m[2])));

  // The shared light-surface block (shadows + stars) folded into each light
  // palette so the generated blocks stand alone.
  const shared = new Map();
  const list = /((?::root\[data-theme='[^']+'\]\s*,\s*)+:root\[data-theme='[^']+'\])\s*\{([^}]*)\}/g;
  for (let m; (m = list.exec(css)); ) {
    for (const id of m[1].matchAll(/data-theme='([^']+)'/g)) {
      shared.set(id[1], new Map(declarations(m[2])));
    }
  }

  const themes = [];
  for (const [id, m] of meta) {
    if (id === 'auto') {
      themes.push({ id, label: m.label, hint: m.hint, scheme: 'auto', swatch: { bg: m.bg, accent: m.accent, fg: m.fg } });
      continue;
    }
    const own = tokens.get(id);
    if (!own) throw new Error(`no token block for theme '${id}'`);
    if (!own.has('color-scheme') && m.scheme) own.set('color-scheme', m.scheme);
    const merged = new Map([...(shared.get(id) ?? []), ...own]);
    themes.push({
      id,
      label: m.label,
      hint: m.hint,
      scheme: merged.get('color-scheme'),
      swatch: { bg: m.bg, accent: m.accent, fg: m.fg },
      tokens: Object.fromEntries(merged),
    });
  }

  writeFileSync(JSON_OUT, `${JSON.stringify({ themes }, null, 2)}\n`);
  return JSON.parse(read(JSON_OUT));
}

function render(data) {
  const parts = [HEADER];
  for (const theme of data.themes) {
    if (!theme.tokens) continue;
    const decls = Object.entries(theme.tokens)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join('\n');
    parts.push(`:root[data-theme='${theme.id}'] {\n  color-scheme: ${theme.scheme};\n${decls}\n}\n`);
  }
  return parts.join('\n');
}

const REQUIRED = [
  '--bg-0', '--bg-1', '--bg-2', '--bg-3',
  '--fg-0', '--fg-1', '--fg-2', '--fg-3',
  '--border', '--border-strong',
  '--accent', '--accent-dim', '--accent-fg', '--accent-soft',
  '--ok', '--warn', '--err', '--info',
];

/** Every palette must be complete, so a half-copied block can't ship. */
function validate(data) {
  for (const theme of data.themes) {
    if (!theme.tokens) continue;
    const missing = REQUIRED.filter((k) => !theme.tokens[k]);
    if (missing.length) {
      console.error(`palette '${theme.id}' is missing: ${missing.join(', ')}`);
      process.exit(1);
    }
  }
}

const args = process.argv.slice(2);
const data = args.includes('--bootstrap') ? bootstrap() : JSON.parse(read(JSON_OUT));
validate(data);
const css = render(data);

if (args.includes('--check')) {
  let bad = false;
  const current = read(CSS_OUT);
  if (current !== css) {
    console.error('styles/themes.css is stale — run `npm run themes`');
    bad = true;
  }

  // The glass layer styles light palettes with a hand-written selector list.
  // Keep it in step with the table instead of silently missing a new theme.
  const appCss = read(join(desktop, 'app.css'));
  const glassIds = new Set(
    [...appCss.matchAll(/:root\[data-glass\]\[data-theme='([^']+)'\]/g)].map((m) => m[1]),
  );
  const lightIds = data.themes
    .filter((t) => t.tokens && t.scheme === 'light')
    .map((t) => t.id);
  const missing = lightIds.filter((id) => !glassIds.has(id));
  const extra = [...glassIds].filter((id) => !lightIds.includes(id));
  if (missing.length || extra.length) {
    console.error(
      `glass light-palette list in app.css is out of date (missing: ${missing.join(', ') || 'none'}; ` +
        `not light: ${extra.join(', ') || 'none'})`,
    );
    bad = true;
  }

  if (bad) process.exit(1);
  console.log(
    `themes.css up to date (${data.themes.filter((t) => t.tokens).length} palettes, ` +
      `${lightIds.length} light)`,
  );
} else {
  mkdirSync(dirname(CSS_OUT), { recursive: true });
  writeFileSync(CSS_OUT, css);
  console.log(`wrote ${CSS_OUT} (${data.themes.filter((t) => t.tokens).length} palettes)`);
}
